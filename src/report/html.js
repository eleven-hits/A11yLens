export function renderHtml(report, options = {}) {
  const summary = report.summary;
  const title = options.title ?? report.config?.reportTitle ?? 'A11yLens Accessibility Audit';
  const scoreClass = summary.score >= 90 ? 'good' : summary.score >= 70 ? 'warn' : 'bad';
  const generated = report.startedAt;
  const findingsHtml = report.findings.length
    ? report.findings.map(findingCard).join('\n')
    : `<div class="empty"><strong>${report.errors?.length ? 'Audit incomplete. Resolve the scan errors before interpreting these results.' : 'No issues found by the automated checks.'}</strong><p>Automated tools cover only part of WCAG. Run the manual screen reader protocol below before claiming conformance.</p></div>`;

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<style>${STYLES}</style>
</head>
<body>
<a class="skip-link" href="#main">Skip to the report</a>
<header class="hero">
  <div class="hero-inner">
    <div class="brand"><span class="logo" aria-hidden="true">A</span> A11yLens</div>
    <h1>${escapeHtml(title)}</h1>
    <p class="target"><code>${escapeHtml(report.root)}</code> · generated ${escapeHtml(generated)} · ${formatMs(report.durationMs)}</p>
    <div class="overview">
      <div class="score-card ${scoreClass}">
        <div class="score-ring" style="--score:${summary.score}" role="img" aria-label="Accessibility score ${summary.score} out of 100">
          <strong>${summary.score}</strong><span>/100</span>
        </div>
        <p>Heuristic score<br><span>not a WCAG conformance score</span></p>
      </div>
      <div class="stat"><span class="stat-value error">${summary.errors}</span><span class="stat-label">Errors</span></div>
      <div class="stat"><span class="stat-value warning">${summary.warnings}</span><span class="stat-label">Warnings</span></div>
      <div class="stat"><span class="stat-value info">${summary.infos}</span><span class="stat-label">Info</span></div>
      <div class="stat"><span class="stat-value">${summary.checks}</span><span class="stat-label">Checks</span></div>
      <div class="stat"><span class="stat-value">${summary.pages}</span><span class="stat-label">Pages</span></div>
    </div>
    <p class="caveat">Automated checks find only part of the barriers. Use the screen reader protocol at the end of this report with NVDA, JAWS, VoiceOver or TalkBack.</p>
  </div>
</header>

<main id="main">
  <section aria-labelledby="findings-title">
    <div class="section-head">
      <h2 id="findings-title">Findings</h2>
      <p class="muted" id="visible-count">${summary.total} finding${summary.total === 1 ? '' : 's'}</p>
    </div>
    <div class="toolbar">
      <label class="search"><span>Search findings</span>
        <input type="search" id="search" placeholder="rule, file, message…" autocomplete="off">
      </label>
      <div class="filters" role="group" aria-label="Filter by severity">
        <button type="button" data-filter="all" aria-pressed="true">All <span>${summary.total}</span></button>
        <button type="button" data-filter="error" aria-pressed="false">Errors <span>${summary.errors}</span></button>
        <button type="button" data-filter="warning" aria-pressed="false">Warnings <span>${summary.warnings}</span></button>
        <button type="button" data-filter="info" aria-pressed="false">Info <span>${summary.infos}</span></button>
      </div>
    </div>
    <div class="findings" id="findings">
${report.truncated ? `<p class="caveat">Showing ${report.findings.length} of ${summary.total} findings. Summary and exit code include all findings.</p>` : ''}
${findingsHtml}
    </div>
  </section>

  ${pageSection(report)}
  ${manualSection()}
  ${aboutSection(report)}
</main>
<footer>
  <p>Generated by A11yLens ${escapeHtml(report.tool.version)} · static analysis${report.dynamic?.enabled ? ` + rendered Chrome scan (axe-core ${escapeHtml(report.dynamic.axeVersion ?? 'n/a')})` : ''}.</p>
  <p>This report lists machine-detectable issues. It is not legal advice and not a conformance certification.</p>
</footer>
<script>
(function () {
  var search = document.getElementById('search');
  var count = document.getElementById('visible-count');
  var cards = Array.prototype.slice.call(document.querySelectorAll('.finding'));
  var buttons = Array.prototype.slice.call(document.querySelectorAll('[data-filter]'));
  var active = 'all';
  function apply() {
    var query = (search.value || '').toLowerCase().trim();
    var shown = 0;
    cards.forEach(function (card) {
      var matchesSeverity = active === 'all' || card.getAttribute('data-severity') === active;
      var matchesText = !query || card.getAttribute('data-search').indexOf(query) !== -1;
      var visible = matchesSeverity && matchesText;
      card.hidden = !visible;
      if (visible) shown += 1;
    });
    count.textContent = shown + ' finding' + (shown === 1 ? '' : 's') + ' shown';
  }
  buttons.forEach(function (button) {
    button.addEventListener('click', function () {
      active = button.getAttribute('data-filter');
      buttons.forEach(function (other) { other.setAttribute('aria-pressed', String(other === button)); });
      apply();
    });
  });
  search.addEventListener('input', apply);
})();
</script>
</body>
</html>
`;
}

function findingCard(finding) {
  const search = `${finding.ruleId} ${finding.title} ${finding.file} ${finding.message} ${finding.severity}`.toLowerCase();
  return `<details class="finding" data-severity="${escapeHtml(finding.severity)}" data-search="${escapeHtml(search)}">
  <summary>
    <span class="sev sev-${escapeHtml(finding.severity)}">${escapeHtml(severityName(finding.severity))}</span>
    <span class="f-main"><span class="f-title">${escapeHtml(finding.message)}</span>
    <span class="f-sub">${escapeHtml(finding.title)}</span></span>
    <span class="f-loc"><code>${escapeHtml(locationLabel(finding))}</code></span>
  </summary>
  <div class="f-body">
    <dl class="meta">
      <div><dt>Rule</dt><dd><code>${escapeHtml(finding.ruleId)}</code></dd></div>
      <div><dt>WCAG</dt><dd>${escapeHtml(finding.wcag.join(', '))} · level ${escapeHtml(finding.level)}</dd></div>
      <div><dt>Engine</dt><dd>${escapeHtml(finding.engine)}</dd></div>
      ${finding.selector ? `<div><dt>Selector</dt><dd><code>${escapeHtml(finding.selector)}</code></dd></div>` : ''}
    </dl>
    ${finding.snippet ? `<pre><code>${escapeHtml(finding.snippet)}</code></pre>` : ''}
    <h3>Screen reader impact</h3>
    <p>${escapeHtml(finding.srImpact)}</p>
    ${finding.manual?.length ? `<ul class="manual">${finding.manual.map((step) => `<li>${escapeHtml(step)}</li>`).join('')}</ul>` : ''}
    <h3>How to fix</h3>
    <p>${escapeHtml(finding.help)}</p>
    ${finding.description ? `<p class="muted">${escapeHtml(finding.description)}</p>` : ''}
    ${finding.helpUrl ? `<p><a href="${escapeHtml(finding.helpUrl)}" rel="noreferrer noopener">${escapeHtml(documentationLabel(finding))}</a></p>` : ''}
  </div>
</details>`;
}

function pageSection(report) {
  const pages = report.pages.filter((page) => page.headings?.length || page.landmarks?.length || page.url);
  if (!pages.length) return '';
  const cards = pages
    .map((page) => {
      const headings = page.headings?.length
        ? `<ol class="outline">${page.headings
            .map(
              (heading) =>
                `<li style="--level:${Math.max(1, Math.min(6, heading.level))}"><span class="h-badge">h${heading.level}</span>${escapeHtml(heading.text || '(empty heading)')}</li>`,
            )
            .join('')}</ol>`
        : '<p class="muted">No headings in the parsed source.</p>';
      const landmarks = page.landmarks?.length
        ? `<div class="chips">${page.landmarks
            .map((landmark) => `<span class="chip">${escapeHtml(landmark.role)}${landmark.name ? ` · ${escapeHtml(landmark.name)}` : ''}</span>`)
            .join('')}</div>`
        : '';
      const rendered = page.render?.outline?.length
        ? `<details class="ax-outline"><summary>Rendered accessibility tree (${page.render.outline.length} nodes)</summary>
            <ul class="outline">
              ${page.render.outline
                .slice(0, 40)
                .map(
                  (entry) =>
                    `<li style="--level:${entry.role === 'heading' ? Math.max(1, Math.min(6, entry.level ?? 2)) : 1}"><span class="h-badge">${escapeHtml(entry.role)}</span>${escapeHtml(entry.text || '(no name)')}</li>`,
                )
                .join('')}
            </ul>
            <p class="counts">${page.render.counts?.focusable ?? 0} focusable nodes · ${page.render.counts?.headings ?? 0} headings · ${page.render.counts?.landmarks ?? 0} landmarks</p>
          </details>`
        : '';
      return `<article class="page-card">
        <h3>${escapeHtml(page.title || page.file)}</h3>
        <p class="muted"><code>${escapeHtml(page.file ?? page.url ?? '')}</code>${page.lang ? ` · lang="${escapeHtml(page.lang)}"` : ''}</p>
        ${rendered}
        <h4>Heading outline</h4>
        ${headings}
        ${landmarks ? `<h4>Landmarks</h4>${landmarks}` : ''}
        ${page.counts ? `<p class="counts">${page.counts.images} images · ${page.counts.links} links · ${page.counts.forms} forms · ${page.counts.ariaLive} live regions</p>` : ''}
      </article>`;
    })
    .join('\n');
  return `<section aria-labelledby="pages-title">
    <div class="section-head"><h2 id="pages-title">Page outlines</h2><p class="muted">What a screen reader sees in the source</p></div>
    <div class="pages">${cards}</div>
  </section>`;
}

function manualSection() {
  const readers = SCREEN_READERS.map(
    (reader) => `<details class="reader">
      <summary><strong>${escapeHtml(reader.name)}</strong> <span class="muted">${escapeHtml(reader.platform)} · ${escapeHtml(reader.cost)}</span></summary>
      <p>${escapeHtml(reader.setup.join(' '))}</p>
      <table><caption>${escapeHtml(reader.name)} keys and actions</caption><thead><tr><th scope="col">Keys</th><th scope="col">Action</th></tr></thead><tbody>
      ${reader.commands.map(([keys, action]) => `<tr><td><kbd>${escapeHtml(keys)}</kbd></td><td>${escapeHtml(action)}</td></tr>`).join('')}
      </tbody></table>
      <p class="muted">${escapeHtml(reader.focus)}</p>
    </details>`,
  ).join('\n');

  return `<section aria-labelledby="manual-title">
    <div class="section-head"><h2 id="manual-title">Manual screen reader protocol</h2><p class="muted">Do this before claiming the site is accessible</p></div>
    <div class="protocol">
      <ol>${MANUAL_PROTOCOL.map((step) => `<li><h3>${escapeHtml(step.title)}</h3><p>${escapeHtml(step.detail)}</p><p><strong>Pass:</strong> ${escapeHtml(step.pass)}</p></li>`).join('')}</ol>
    </div>
    <div class="readers">${readers}</div>
  </section>`;
}

function aboutSection(report) {
  return `<section aria-labelledby="about-title">
    <div class="section-head"><h2 id="about-title">About this audit</h2><p class="muted">Scope, limits and configuration</p></div>
    <div class="about-grid">
      <div>
        <h3>What was scanned</h3>
        <ul>
          <li>${report.files.html.length} HTML document(s)</li>
          <li>${report.files.source.length} component source file(s)</li>
          <li>${report.files.css.length} stylesheet(s)</li>
          <li>${report.pages.length} page(s) in the report</li>
          ${report.dynamic?.enabled ? `<li>${report.dynamic.pageCount} rendered page(s) in ${escapeHtml(report.dynamic.browser ?? 'Chrome')}</li>` : '<li>Rendered scan disabled (use --render to include Chrome, axe-core and the accessibility tree)</li>'}
        </ul>
        <h3>Rules</h3>
        <p>${report.rulesExecuted.length} checks were executed. Automated checks cannot judge whether an announcement makes sense, whether the reading order is logical, or whether a custom widget is usable.</p>
      </div>
      <div>
        <h3>Limits of automation</h3>
        <ul>${AUTOMATION_LIMITS.map((limit) => `<li>${escapeHtml(limit)}</li>`).join('')}</ul>
        ${report.errors?.length ? `<h3>Internal notes</h3><ul>${report.errors.slice(0, 10).map((entry) => `<li><code>${escapeHtml(entry.file)}</code>: ${escapeHtml(entry.message)}</li>`).join('')}</ul>` : ''}
        ${report.baseline?.suppressed ? `<p class="muted">Baseline suppressed ${report.baseline.suppressed} known finding(s).</p>` : ''}
      </div>
    </div>
  </section>`;
}

function severityName(severity) {
  if (severity === 'error') return 'Error';
  if (severity === 'warning') return 'Warning';
  return 'Info';
}

function documentationLabel(finding) {
  if (finding.engine === 'axe') return `axe-core rule documentation (${finding.ruleId.replace(/^axe\//, '')})`;
  if (!finding.wcag?.length) return 'Rule documentation';
  return `Understanding WCAG ${finding.wcag.join(', ')}`;
}

